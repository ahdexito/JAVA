package prog02_3ejer02;

public class Prog02_3ejer02 
{

     public static void main(String[] args)
     {
	  /*
	  Escribir un programa que muestre en pantalla los números enteros del 1 al 100 de 2 en 2
	  empleando la estructura ‘for’.
	  */
	  
	  for(int i=1; i<=100; i+=2)
	  {
	       System.out.print(i + ", ");
	  }
     }
     
}
