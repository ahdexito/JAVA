package prog02_3ejer03;

public class Prog02_3ejer03 
{

     public static void main(String[] args) 
     {
	  /*
	  Escribir un programa que muestre en pantalla los números enteros del 100 al 1 empleando
	  la estructura ‘for’.
	  */
	  
	  for(int i=100; i>0; i--)
	  {
	       System.out.print(i + ", ");
	  }
     }
     
}
